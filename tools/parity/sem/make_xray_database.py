#!/usr/bin/env python
"""tools/parity/sem/make_xray_database.py — write Sources/TEMCore/EDX/XrayLineDatabase.swift from exspy's element database.

    make_xray_database.py OUT.swift

The SEM-EDS port (SEMEDSLines) reads the X-ray line energies, line weights and atomic weights exactly as exspy 0.3.2 holds
them in `exspy._misc.elements.elements` (GPL-3.0-or-later): every element in the dict's own order, every line in the
element's own order, each float written with Python's shortest round-trip repr so the Swift literal is the same double.
The bundle `m7/eds-xray-database` (emit.py) holds the same table and `SEMEDSParityTests` compares the two exactly, so a
pin that moves the database is red until this file is regenerated. Run with `python -I -B` from the pinned venv.
"""

import sys

from exspy._misc.elements import elements as db

HEAD = """//
//  XrayLineDatabase.swift
//  Role: the X-ray lines and atomic weights of exspy 0.3.2's element database (`exspy._misc.elements.elements`, eXSpy,
//        GPL-3.0-or-later, taken under GPL-3.0), the table SEM-EDS line selection, windows and the weight-to-atomic
//        conversion read. GENERATED by tools/parity/sem/make_xray_database.py; do not edit by hand. Elements and lines keep
//        the dict's order; energies are keV, weights are exspy's relative line weights. Parity: `m7/eds-xray-database`,
//        exact (SEMEDSParityTests).
//

package nonisolated enum XrayLineDatabase {
    package struct Line: Equatable, Sendable {
        /// The subshell name as exspy writes it (`Ka`, `La`, `Lb3`, `M2N4`, …).
        package let name: String
        package let energyKeV: Double
        package let weight: Double
    }

    package struct Element: Equatable, Sendable {
        package let symbol: String
        package let z: Int
        package let atomicWeight: Double
        /// Empty for the elements exspy lists without X-ray lines (Li, Np, Pu, Am).
        package let lines: [Line]
    }

    /// Every element, in exspy's order.
    package static let elements: [Element] = [
"""

TAIL = """    ]

    private static let bySymbol: [String: Element] = Dictionary(uniqueKeysWithValues: elements.map { ($0.symbol, $0) })

    /// The element named by `symbol`, or nil when exspy's database has no such element.
    package static func element(_ symbol: String) -> Element? { bySymbol[symbol] }

    /// The line `Element_Subshell` (`Mn_Ka`), or nil when the element or the subshell is not in the database.
    package static func line(_ xrayLine: String) -> Line? {
        let parts = xrayLine.split(separator: "_", maxSplits: 1).map(String.init)
        guard parts.count == 2, let element = bySymbol[parts[0]] else { return nil }
        return element.lines.first { $0.name == parts[1] }
    }
}
"""


def main(out: str) -> int:
    rows = []
    for el, d in db.items():
        gp = d["General_properties"]
        lines = d["Atomic_properties"].get("Xray_lines", {})
        ls = ", ".join(
            f'.init(name: "{ln}", energyKeV: {float(v["energy (keV)"])!r}, weight: {float(v["weight"])!r})' for ln, v in lines.items()
        )
        rows.append(
            f'        .init(symbol: "{el}", z: {int(gp["Z"])}, atomicWeight: {float(gp["atomic_weight"])!r}, lines: [{ls}]),'
        )
    with open(out, "w", encoding="utf-8") as f:
        f.write(HEAD + "\n".join(rows) + "\n" + TAIL)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
