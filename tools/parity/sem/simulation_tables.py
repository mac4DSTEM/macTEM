#!/usr/bin/env python
"""tools/parity/sem/simulation_tables.py — write TEMCore's Kikuchi scattering tables from the pinned diffsims.

    References/sem-venv/bin/python -I -B tools/parity/sem/simulation_tables.py \
        > Sources/TEMCore/SEM/Simulation/KikuchiScatteringTables.swift

diffsims 0.7.0's two parameter tables, carried by this script, not by hand: the X-ray parameters of the International
Tables (vol. C, table 4.3.2.3; `diffsims.utils.atomic_scattering_params.ATOMIC_SCATTERING_PARAMS`, five (a, b) pairs per
element symbol), which `ReciprocalLatticeVector.calculate_structure_factor` uses, and Doyle & Turner's electron parameters
(De Graef & McHenry 2007, table 12.1; `ATOMIC_SCATTERING_PARAMETERS_DOYLETURNER`, a1..a4, b1..b4 for Z = 1..98), which the
refraction-corrected wavelength uses. The bundle `m6/kikuchi-scattering-tables` holds both, and the Swift test compares
every number with it exactly. Values are printed with repr, so the Swift literal is the same double.
"""

from diffsims.structure_factor.atomic_scattering_parameters import ATOMIC_SCATTERING_PARAMETERS_DOYLETURNER, ELEMENTS
from diffsims.utils.atomic_scattering_params import ATOMIC_SCATTERING_PARAMS

out = []
w = out.append
w("//")
w("//  KikuchiScatteringTables.swift")
w("//  GENERATED by tools/parity/sem/simulation_tables.py from diffsims 0.7.0 (GPL-3.0-or-later, see NOTICE); do not edit by hand.")
w("//  The X-ray parameters of the International Tables vol. C, table 4.3.2.3 (diffsims' `ATOMIC_SCATTERING_PARAMS`: five (a, b)")
w("//  pairs per element symbol, f(s) = sum a exp(-b s^2), s = g / 2) and Doyle & Turner's electron parameters (Acta Cryst. A24, 390,")
w("//  1968, via De Graef & McHenry 2007, table 12.1: a1..a4, b1..b4 in 1/A^2 for Z = 1..98). Parity bundle m6/kikuchi-scattering-tables.")
w("//")
w("")
w("package nonisolated enum KikuchiScatteringTables {")
w("    /// The X-ray table's element symbols, in diffsims' order.")
w("    package static let xraySymbols: [String] = [")
syms = list(ATOMIC_SCATTERING_PARAMS.keys())
for i in range(0, len(syms), 16):
    w("        " + ", ".join(f'"{s}"' for s in syms[i:i + 16]) + ",")
w("    ]")
w("    /// Row per symbol of `xraySymbols`: [a1, b1, a2, b2, ..., a5, b5].")
w("    package static let xray: [[Double]] = [")
for s in syms:
    vals = [repr(float(x)) for pair in ATOMIC_SCATTERING_PARAMS[s] for x in pair]
    w("        [" + ", ".join(vals) + "],  // " + s)
w("    ]")
w("    /// Lower-case element names by Z - 1 (diffsims' `ELEMENTS`, Z = 1..98).")
w("    package static let doyleTurnerElements: [String] = [")
el = list(ELEMENTS[:98])
for i in range(0, len(el), 16):
    w("        " + ", ".join(f'"{s}"' for s in el[i:i + 16]) + ",")
w("    ]")
w("    /// Row Z - 1: [a1, a2, a3, a4, b1, b2, b3, b4] in 1/A^2.")
w("    package static let doyleTurner: [[Double]] = [")
for z, row in enumerate(ATOMIC_SCATTERING_PARAMETERS_DOYLETURNER):
    w("        [" + ", ".join(repr(float(x)) for x in row) + "],  // " + el[z])
w("    ]")
w("}")
print("\n".join(out))
